/* Builds the parts catalog: for every section (the live gallery excluded), the captured screens a
   customer can pick as the reference, in the same order the step 3 preview tries them.
     v4/data/parts.json                 read by the page and the order page
     v3/backend/parts-snapshot.gs       read by brief-sync.gs (never trusts the browser's copy)
     deploy/apps-script/parts-snapshot.gs  the copy clasp pushes
   A ref is `<sampleId>:<slug>` and is unique only inside its section; always check (section, ref).
   Run: node scripts/v4-parts.mjs   (tests/v4/parts.test.mjs fails when the outputs are stale) */
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = new URL('..', import.meta.url);
const read = (p) => JSON.parse(readFileSync(new URL(p, root), 'utf8'));

// Where the page's assets are served once v4 is deployed (the order page and gs build links from it).
export const ASSET_BASE = 'https://getsite-my.web.app/v4/';
export const slugOf = (selector) => selector === '__hero__' ? 'hero' : selector.replace(/^[#.]/, '').replace(/[^A-Za-z0-9_-]+/g, '-');

export function buildParts({ sections, samples, manifest, motion = null }) {
  const sampleById = Object.fromEntries(samples.map((s) => [s.id, s]));
  const bySection = {};
  for (const sec of sections) {
    if (sec.live) continue;
    const seen = new Set();
    const list = [];
    const cands = sec.previews.flatMap((p) => (p.sample === '*' ? samples.map((s) => ({ sample: s.id, selector: p.selector })) : [p]));
    for (const p of cands) {
      const sample = sampleById[p.sample];
      const m = manifest[p.sample];
      if (!sample || !m) continue;
      const slug = slugOf(p.selector);
      let e;
      if (p.selector === '__hero__') {
        if (!m.hero) continue;
        e = { file: m.hero, thumb: m.hero.replace(/\.webp$/, '-640.webp'), w: 1440, h: 900 };
      } else {
        const c = m[slug];
        if (!c?.file) continue;
        e = { file: c.file, thumb: c.thumb || c.file, w: c.w, h: c.h };
      }
      const ref = `${p.sample}:${slug}`;
      if (seen.has(ref)) continue;
      seen.add(ref);
      // Only an id selector is a link target on the sample's page; a class selector links to the page.
      const anchor = p.selector.startsWith('#') ? `${sample.url.replace(/#.*$/, '')}#${slug}` : sample.url;
      list.push({ ref, sampleId: p.sample, slug, file: `assets/samples/${p.sample}/${e.file}`, thumb: `assets/samples/${p.sample}/${e.thumb}`, w: e.w, h: e.h, anchor });
    }
    // The hero also offers the motion scenes (v4/data/motion-scenes.json), after the still captures, each
    // with its poster; a scene without a captured poster is left out (run scripts/v4-capture-motion.mjs).
    if (sec.id === 'hero' && motion) {
      const m = manifest[motion.sampleId] || {};
      for (const sc of motion.scenes) {
        const c = m[sc.slug];
        if (!c?.file || !sampleById[motion.sampleId]) continue;
        list.push({ ref: `${motion.sampleId}:${sc.slug}`, sampleId: motion.sampleId, slug: sc.slug, file: `assets/samples/${motion.sampleId}/${c.file}`, thumb: `assets/samples/${motion.sampleId}/${c.thumb}`, w: c.w, h: c.h, anchor: `${motion.publicUrl}#scene=${sc.index}`, kind: 'motion', scene: sc.index, name: sc.name, hint: sc.hint, ...(sc.video ? { video: true } : {}) });
      }
    }
    bySection[sec.id] = list;
  }
  const version = `p-${createHash('sha1').update(JSON.stringify([bySection, motion?.videoNote || ''])).digest('hex').slice(0, 10)}`;
  const extra = motion ? { motion: { sampleId: motion.sampleId, page: motion.page, videoNote: motion.videoNote } } : {};
  return { version, assetBase: ASSET_BASE, ...extra, bySection };
}

/** What the Apps Script needs: titles and concepts from samples.json, and (section, ref) → links. */
export function snapshot(parts, samples) {
  const data = {
    version: parts.version,
    assetBase: parts.assetBase,
    videoNote: parts.motion?.videoNote || '',
    samples: Object.fromEntries(samples.map((s) => [s.id, { title: s.title, url: s.url, topic: s.topic, concept: s.concept }])),
    bySection: Object.fromEntries(Object.entries(parts.bySection).map(([id, list]) => [id, Object.fromEntries(list.map((p) => [p.ref, { sampleId: p.sampleId, slug: p.slug, file: p.file, anchor: p.anchor, ...(p.kind ? { kind: p.kind, name: p.name } : {}), ...(p.video ? { video: true } : {}) }]))])),
  };
  return `// Generated by scripts/v4-parts.mjs. Do not edit.\nvar PARTS = ${JSON.stringify(data, null, 2)};\n`;
}

export function outputs() {
  const { sections } = read('v4/data/sections.json');
  const { samples } = read('v4/data/samples.json');
  const manifest = read('v4/assets/samples/manifest.json');
  const motion = read('v4/data/motion-scenes.json');
  const parts = buildParts({ sections, samples, manifest, motion });
  return { parts, json: `${JSON.stringify(parts, null, 2)}\n`, gs: snapshot(parts, samples) };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { parts, json, gs } = outputs();
  writeFileSync(new URL('v4/data/parts.json', root), json);
  writeFileSync(new URL('v3/backend/parts-snapshot.gs', root), gs);
  writeFileSync(new URL('deploy/apps-script/parts-snapshot.gs', root), gs);
  const counts = Object.entries(parts.bySection).map(([k, v]) => `${k} ${v.length}`).join(', ');
  console.log(`parts ${parts.version}: ${counts}`);
}
