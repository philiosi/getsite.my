// Regenerates catalog-snapshot.gs from v3/catalog.js. Run: node v3/backend/build-catalog.mjs
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import * as c from '../catalog.js';

export function snapshot() {
  const tokens = ({ fontDisplay, weightDisplay, trackDisplay, ...colors }) => ({ colors, fontDisplay, weightDisplay, trackDisplay });
  const map = (list, fn) => Object.fromEntries(list.map((x) => [x.id, fn(x)]));
  const data = {
    version: c.CATALOG_VERSION,
    concepts: map(c.CONCEPTS, (x) => ({
      name: x.name,
      tokens: tokens(x.tokens),
      sections: x.sections.map((id) => c.SECTION_LABELS[id]),
      sites: x.real.map((id) => c.REAL_SITES[id].url),
    })),
    scenes: map(c.SCENES, (x) => ({ name: x.name, impl: x.impl, spec: x.spec })),
    galleries: map(c.GALLERIES, (x) => ({ name: x.name, impl: x.impl, spec: x.spec })),
  };
  return `// Generated by build-catalog.mjs. Do not edit.\nvar CATALOG = ${JSON.stringify(data, null, 2)};\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(new URL('./catalog-snapshot.gs', import.meta.url), snapshot());
}
